"""Render the pinned encoder tests from the same vectors Rust consumes."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "crates/bloom-evm-clear-signing/tests/fixtures/weiroll"


def render(vectors):
    lines = ["// Generated by scripts/weiroll_vectors.py; edit vectors.json.",
             "pragma solidity ^0.8.20;", "import {CommandBuilder} from './CommandBuilder.sol';",
             "contract ShortcutDifferential {"]
    for index, vector in enumerate(vectors):
        state = vector["state"]
        lines += [f"function testCase{index}() public view {{", f"bytes[] memory state = new bytes[]({len(state)});"]
        lines += [f'state[{i}]=hex"{value}";' for i, value in enumerate(state)]
        if vector["flags"] & 0x20:
            # VM FLAG_DATA bypasses CommandBuilder and copies this slot verbatim.
            slot = bytes.fromhex(vector["indices"])[1 if vector["flags"] & 3 == 3 else 0] & 0x7f
            lines += [f"bytes memory actual=state[{slot}];"]
        else:
            lines += [f'bytes memory actual=CommandBuilder.buildInputs(state,hex"{vector["selector"]}",hex"{vector["indices"]}",32);']
        lines += [f'require(keccak256(actual)==keccak256(hex"{vector["calldata"]}"),"vector {index}");', "}"]
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(json.loads((ROOT / "vectors.json").read_text()))
    target = ROOT / "ShortcutDifferential.t.sol"
    if args.check:
        if target.read_text() != expected:
            raise SystemExit("Encoder tests differ from vectors.json; run scripts/weiroll_vectors.py")
    else:
        target.write_text(expected)
